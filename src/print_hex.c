#include "ft_printf.h"

int	print_hex(char c, unsigned int n)
{
	int	res;

	if (c == 'x')
		putbase(n, "0123456789abcdef");
	else
		putbase(n, "0123456789ABCDEF");
	res = 1;
	while (n >= 16)
	{
		n /= 16;
		res++;
	}
	return (res);
}
