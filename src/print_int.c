#include "ft_printf.h"

int	print_int(int n)
{
	int		res;
	long	nb;

	res = 1;
	nb = n;
	if (nb < 0)
	{
		nb = -nb;
		res++;
	}
	while (nb > 9)
	{
		nb /= 10;
		res++;
	}
	return (ft_putnbr_fd(n, 1), res);
}
